"""Per-MTI rule selection, register capture, and response rendering."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path


REGISTER_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


@dataclass(frozen=True)
class OutboundAction:
    message_path: Path
    expect_response: bool = True


def load_json_object(path: str | Path, description: str) -> dict:
    source_path = Path(path).expanduser()
    try:
        with source_path.open("r", encoding="utf-8") as source:
            value = json.load(source)
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"cannot load {description} {source_path}: {exc}") from exc
    if not isinstance(value, dict):
        raise ValueError(f"{description} {source_path} must contain a JSON object")
    return value


def split_operations(expression: str) -> list[str]:
    operations = []
    start = 0
    escaped = False
    for index, char in enumerate(expression):
        if char == ";" and not escaped:
            operations.append(expression[start:index])
            start = index + 1
        escaped = char == "\\" and not escaped
    operations.append(expression[start:])
    if any(not operation for operation in operations):
        raise ValueError(f"empty operation in expression: {expression!r}")
    return operations


def read_slash_segment(text: str, start: int) -> tuple[str, int]:
    value = []
    index = start
    while index < len(text):
        char = text[index]
        if char == "/":
            return "".join(value), index + 1
        if char == "\\" and index + 1 < len(text) and text[index + 1] in ("/", ";"):
            value.append(text[index + 1])
            index += 2
            continue
        value.append(char)
        index += 1
    raise ValueError(f"unterminated slash expression: {text!r}")


def parse_operation(text: str) -> tuple[str, str, str]:
    if text == "//":
        return "echo", "", ""
    if not text.startswith("/"):
        raise ValueError(f"invalid response operation: {text!r}")
    pattern, next_index = read_slash_segment(text, 1)
    replacement, end = read_slash_segment(text, next_index)
    if end != len(text):
        raise ValueError(f"unexpected text after substitution: {text!r}")
    return "substitute", pattern, replacement


def parse_template(template: dict) -> dict[str, list[tuple[str, str, str]]]:
    parsed = {}
    for field, expression in template.items():
        if field in ("p", "1"):
            raise ValueError(f"field {field} is generated by the encoder and cannot be templated")
        if not isinstance(field, str) or not isinstance(expression, str):
            raise ValueError("response template fields and expressions must be strings")
        parsed[field] = [parse_operation(item) for item in split_operations(expression)]
    return parsed


def expand_replacement(
    replacement: str,
    registers: dict[str, str],
    match: re.Match[str] | None = None,
) -> str:
    marker = "\x00DOLLAR\x00"
    text = replacement.replace("$$", marker)

    def replace_reference(found: re.Match[str]) -> str:
        reference = found.group(1)
        if reference.isdigit():
            if match is None:
                raise ValueError(f"capture group ${reference} is unavailable in {replacement!r}")
            try:
                return match.group(int(reference)) or ""
            except IndexError as exc:
                raise ValueError(f"capture group ${reference} does not exist") from exc
        if reference not in registers:
            raise ValueError(f"register ${reference} is undefined")
        return registers[reference]

    text = re.sub(r"\$([A-Za-z_][A-Za-z0-9_]*|[0-9]+)", replace_reference, text)
    return text.replace(marker, "$")


def render_response(
    request: dict[str, str], template: dict, registers: dict[str, str] | None = None
) -> dict[str, str]:
    operations = parse_template(template)
    registers = dict(registers or {})
    response = {}
    for field, field_operations in operations.items():
        if field in request:
            value = request[field]
            for operation, pattern, replacement in field_operations:
                if operation == "substitute":
                    value = re.sub(
                        pattern,
                        lambda found: expand_replacement(replacement, registers, found),
                        value,
                    )
            response[field] = value
            continue

        substitutions = [item for item in field_operations if item[0] == "substitute"]
        echoes = [item for item in field_operations if item[0] == "echo"]
        if echoes and not substitutions:
            continue
        if len(substitutions) != 1 or echoes:
            raise ValueError(f"new field {field} must contain exactly one substitution")
        response[field] = expand_replacement(substitutions[0][2], registers)
    return response


def luhn_valid(value: str) -> bool:
    if not value or not value.isdigit():
        return False
    total = 0
    parity = len(value) % 2
    for index, char in enumerate(value):
        digit = int(char)
        if index % 2 == parity:
            digit = digit * 2 - 9 if digit > 4 else digit * 2
        total += digit
    return total % 10 == 0


def parse_date_value(value: str, date_format: str) -> datetime | None:
    has_year = "%Y" in date_format or "%y" in date_format
    parse_value = value if has_year else "2000" + value
    parse_format = date_format if has_year else "%Y" + date_format
    try:
        parsed = datetime.strptime(parse_value, parse_format)
    except ValueError:
        return None
    if parsed.strftime(date_format) != value:
        return None
    return parsed


def date_matches_now(
    parsed: datetime,
    date_format: str,
    now: datetime,
    tolerance_seconds: float,
) -> bool:
    has_year = "%Y" in date_format or "%y" in date_format
    has_date = any(token in date_format for token in ("%m", "%d", "%j"))
    has_time = any(token in date_format for token in ("%H", "%I", "%M", "%S"))
    tolerance = timedelta(seconds=tolerance_seconds)

    if has_date and has_time:
        years = (parsed.year,) if has_year else (now.year - 1, now.year, now.year + 1)
        for year in years:
            try:
                candidate = parsed.replace(year=year)
            except ValueError:
                continue
            if abs(candidate - now) <= tolerance:
                return True
        return False

    if has_time and not has_date:
        candidate = datetime.combine(now.date(), parsed.time())
        return min(abs(candidate + timedelta(days=offset) - now) for offset in (-1, 0, 1)) <= tolerance

    if has_date:
        years = (parsed.year,) if has_year else (now.year - 1, now.year, now.year + 1)
        candidates = []
        for year in years:
            try:
                candidates.append(parsed.replace(year=year).date())
            except ValueError:
                continue
        if now.date() in candidates:
            return True
        start_today = datetime.combine(now.date(), datetime.min.time())
        if now.date() - timedelta(days=1) in candidates:
            return now - start_today <= tolerance
        if now.date() + timedelta(days=1) in candidates:
            return start_today + timedelta(days=1) - now <= tolerance
    return False


class ResponseEngine:
    def __init__(self, rules_path: str | Path) -> None:
        self.rules_path = Path(rules_path).expanduser().resolve()
        document = load_json_object(self.rules_path, "MTI rules index")
        metadata = {key: value for key, value in document.items() if key.startswith("_")}
        self.index = {key: value for key, value in document.items() if not key.startswith("_")}
        if not all(isinstance(mti, str) and (isinstance(path, str) or path is None)
                   for mti, path in self.index.items()):
            raise ValueError("MTI rules index values must be rule paths or null")
        self.validation_profile = None
        profile_reference = metadata.get("_validation_profile")
        if profile_reference is not None:
            if not isinstance(profile_reference, str):
                raise ValueError("_validation_profile must be a JSON path")
            profile_path = (self.rules_path.parent / profile_reference).resolve()
            self.validation_profile = load_json_object(profile_path, "validation profile")
        self.format_error_reference = metadata.get("_format_error_response")
        if self.format_error_reference is not None and not isinstance(self.format_error_reference, str):
            raise ValueError("_format_error_response must be a response path")
        self.rule_sets = {}
        self.templates = {}

    def _validate_structure(self, request: dict[str, str]) -> list[str]:
        if self.validation_profile is None:
            return []
        mti = request.get("t")
        definition = self.validation_profile.get(mti)
        if not isinstance(definition, dict):
            return [f"MTI {mti or '<missing>'} is not supported by this profile"]
        required = definition.get("required", [])
        if not isinstance(required, list) or not all(isinstance(field, str) for field in required):
            raise ValueError(f"validation profile for MTI {mti} requires a string list named required")
        return [f"missing DE{field}" for field in required if field not in request]

    def _rule_set(self, relative_path: str) -> tuple[Path, dict]:
        path = (self.rules_path.parent / relative_path).resolve()
        if path not in self.rule_sets:
            document = load_json_object(path, "MTI rules file")
            if not isinstance(document.get("captures", {}), dict) or not isinstance(document.get("rules", []), list):
                raise ValueError(f"MTI rules file {path} requires captures and rules objects")
            if document.get("default") is not None and not isinstance(document.get("default"), str):
                raise ValueError(f"default in {path} must be a response path or null")
            tolerance = document.get("date_now_tolerance", 300)
            if not isinstance(tolerance, (int, float)) or isinstance(tolerance, bool) or tolerance < 0:
                raise ValueError(f"date_now_tolerance in {path} must be a non-negative number")
            self.rule_sets[path] = document
        return path, self.rule_sets[path]

    def _template(self, rules_file: Path, relative_path: str) -> tuple[Path, dict]:
        path = (rules_file.parent / relative_path).resolve()
        if path not in self.templates:
            self.templates[path] = load_json_object(path, "response template")
            parse_template(self.templates[path])
        return path, self.templates[path]

    @staticmethod
    def _capture_registers(
        request: dict[str, str],
        captures: dict,
        date_now_tolerance: float,
        now: datetime | None = None,
    ) -> dict[str, str]:
        registers = {}
        current = now or datetime.now()
        for reference, capture in captures.items():
            if not isinstance(reference, str) or not reference.startswith("$"):
                raise ValueError(f"capture name {reference!r} must start with $")
            name = reference[1:]
            if not REGISTER_NAME.fullmatch(name) or not isinstance(capture, dict):
                raise ValueError(f"invalid register capture: {reference!r}")
            field = capture.get("field")
            if not isinstance(field, str):
                raise ValueError(f"capture {reference} requires a string field")
            if name.startswith("date"):
                if name.endswith("_now"):
                    raise ValueError(f"{reference} is derived automatically and cannot be captured")
                date_format = capture.get("format")
                if not isinstance(date_format, str) or not date_format:
                    raise ValueError(f"date capture {reference} requires a format")
                if field not in request:
                    continue
                parsed = parse_date_value(request[field], date_format)
                registers[name] = "1" if parsed else "0"
                registers[name + "_now"] = (
                    "1"
                    if parsed and date_matches_now(parsed, date_format, current, date_now_tolerance)
                    else "0"
                )
                continue
            pattern = capture.get("regex")
            if not isinstance(pattern, str):
                raise ValueError(f"capture {reference} requires a regex")
            if field not in request or (found := re.search(pattern, request[field])) is None:
                continue
            value = found.group(1) if found.lastindex else found.group(0)
            registers[name] = ("1" if luhn_valid(value) else "0") if name == "luhn" else value
        return registers

    @staticmethod
    def _matches(conditions: dict, request: dict[str, str], registers: dict[str, str]) -> bool:
        for reference, pattern in conditions.items():
            if not isinstance(reference, str) or not isinstance(pattern, str):
                raise ValueError("match keys and regex conditions must be strings")
            value = registers.get(reference[1:]) if reference.startswith("$") else request.get(reference)
            if value is None or re.search(pattern, value) is None:
                return False
        return True

    def respond_malformed(self, raw: bytes, reason: str) -> tuple[dict[str, str] | None, str, Path | None]:
        """Use configured format-error template when the wire cannot be decoded.

        Only the four-byte ASCII MTI is trusted. No fields are recovered from a
        damaged bitmap, and no synthetic correlation identifiers are invented.
        """
        mti = raw[:4].decode("ascii", errors="replace")
        if (len(raw) < 4 or not mti.isascii() or not mti.isdigit()
                or mti not in self.index or self.index[mti] is None):
            return None, f"malformed message (no recoverable MTI): {reason}", None
        if self.format_error_reference is None:
            return None, f"malformed message (no configured error response): {reason}", None
        path, template = self._template(self.rules_path, self.format_error_reference)
        response = render_response({"t": mti}, template)
        return response, f"malformed message: {reason}", path

    def respond(self, request: dict[str, str]) -> tuple[dict[str, str] | None, str, Path | None]:
        rules_reference = self.index.get(request.get("t"))
        if rules_reference is None:
            return None, "no rules for MTI", None
        rules_file, rule_set = self._rule_set(rules_reference)
        structure_errors = self._validate_structure(request)
        if structure_errors:
            if self.format_error_reference is None:
                return None, "format error: " + ", ".join(structure_errors), None
            path, template = self._template(self.rules_path, self.format_error_reference)
            return (
                render_response(request, template),
                "format error: " + ", ".join(structure_errors),
                path,
            )
        registers = self._capture_registers(
            request,
            rule_set.get("captures", {}),
            rule_set.get("date_now_tolerance", 300),
        )
        for index, rule in enumerate(rule_set.get("rules", [])):
            if not isinstance(rule, dict) or not isinstance(rule.get("match"), dict) or not isinstance(rule.get("response"), str):
                raise ValueError(f"rule {index} requires match and response")
            if self._matches(rule["match"], request, registers):
                path, template = self._template(rules_file, rule["response"])
                return render_response(request, template, registers), str(rule.get("name", index)), path
        default = rule_set.get("default")
        if default is None:
            return None, "default: no response", None
        path, template = self._template(rules_file, default)
        return render_response(request, template, registers), "default", path


class ClientFlowEngine:
    """Stateful client-side rules that select each outbound message."""

    def __init__(self, rules_path: str | Path) -> None:
        self.rules_path = Path(rules_path).expanduser().resolve()
        self.document = load_json_object(self.rules_path, "client flow rules")
        responses = self.document.get("responses", {})
        if not isinstance(responses, dict) or not all(
            isinstance(mti, str) and isinstance(path, str)
            for mti, path in responses.items()
        ):
            raise ValueError("client flow responses must map MTIs to rule files")
        self.responses = responses
        heartbeat = self.document.get("heartbeat", {"enabled": False})
        if not isinstance(heartbeat, dict):
            raise ValueError("client heartbeat must be an object")
        self.heartbeat_enabled = heartbeat.get("enabled", False)
        interval = heartbeat.get("interval_seconds", 60)
        message = heartbeat.get("message")
        expect_response = heartbeat.get("expect_response", True)
        if not isinstance(self.heartbeat_enabled, bool) or not isinstance(interval, (int, float)) or isinstance(interval, bool) or interval <= 0 or not isinstance(expect_response, bool):
            raise ValueError("invalid client heartbeat configuration")
        if self.heartbeat_enabled and (not isinstance(message, str) or not message):
            raise ValueError("enabled heartbeat requires message path")
        self.heartbeat_interval = float(interval)
        self.heartbeat_action = OutboundAction((self.rules_path.parent / message).resolve(), expect_response) if self.heartbeat_enabled else None
        self.registers: dict[str, str] = {}
        self.rule_sets: dict[Path, dict] = {}
        if "start" not in self.document:
            raise ValueError("client flow rules require a start action")

    @staticmethod
    def _action(value: object, base: Path, description: str) -> OutboundAction | None:
        if value is None:
            return None
        if isinstance(value, str):
            return OutboundAction((base / value).resolve(), True)
        if not isinstance(value, dict):
            raise ValueError(f"{description} must be a message path, action object, or null")
        message = value.get("message")
        expect_response = value.get("expect_response", True)
        if not isinstance(message, str) or not isinstance(expect_response, bool):
            raise ValueError(f"{description} requires message and boolean expect_response")
        return OutboundAction((base / message).resolve(), expect_response)

    def start(self) -> OutboundAction:
        action = self._action(self.document["start"], self.rules_path.parent, "start")
        if action is None:
            raise ValueError("client flow start cannot be null")
        return action

    def _rule_set(self, relative_path: str) -> tuple[Path, dict]:
        path = (self.rules_path.parent / relative_path).resolve()
        if path not in self.rule_sets:
            document = load_json_object(path, "client response rules")
            if not isinstance(document.get("captures", {}), dict) or not isinstance(document.get("rules", []), list):
                raise ValueError(f"client response rules {path} require captures and rules")
            tolerance = document.get("date_now_tolerance", 300)
            if not isinstance(tolerance, (int, float)) or isinstance(tolerance, bool) or tolerance < 0:
                raise ValueError(f"date_now_tolerance in {path} must be a non-negative number")
            self.rule_sets[path] = document
        return path, self.rule_sets[path]

    def next(self, response: dict[str, str]) -> tuple[OutboundAction | None, str]:
        relative_path = self.responses.get(response.get("t"))
        if relative_path is None:
            return None, "no client rules for MTI"
        rules_file, rule_set = self._rule_set(relative_path)
        captured = ResponseEngine._capture_registers(
            response,
            rule_set.get("captures", {}),
            rule_set.get("date_now_tolerance", 300),
        )
        self.registers.update(captured)
        for index, rule in enumerate(rule_set.get("rules", [])):
            if not isinstance(rule, dict) or not isinstance(rule.get("match"), dict) or "next" not in rule:
                raise ValueError(f"client rule {index} requires match and next")
            if ResponseEngine._matches(rule["match"], response, self.registers):
                return (
                    self._action(rule["next"], rules_file.parent, f"client rule {index} next"),
                    str(rule.get("name", index)),
                )
        return self._action(rule_set.get("default"), rules_file.parent, "client default"), "default"
